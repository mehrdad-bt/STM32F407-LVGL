#include "Application.h"

#include "main.h"

#include "lvgl.h"

#include "LCDController.h"
#include "TouchController.h"

#include "ui/ui.h"

#include "AHT10.h"

#include "MainPage.h"
#include "TempPage.h"

#include "Tasks.h"


extern I2C_HandleTypeDef hi2c1;
extern SPI_HandleTypeDef hspi1;


/* -------------------------------------------------------------------------- */
/* Application Initialization                                                 */
/* -------------------------------------------------------------------------- */

void Application_Init(void)
{
    /* ---------------------------------------------------------------------- */
    /* AHT10                                                                  */
    /* ---------------------------------------------------------------------- */

    AHT10_Init(
        &hi2c1
    );


    /* ---------------------------------------------------------------------- */
    /* LVGL                                                                    */
    /* ---------------------------------------------------------------------- */

    lv_init();


    /* ---------------------------------------------------------------------- */
    /* LCD                                                                      */
    /* ---------------------------------------------------------------------- */

    lv_port_disp_init();


    /* ---------------------------------------------------------------------- */
    /* XPT2046                                                                  */
    /* ---------------------------------------------------------------------- */

    XPT2046_Init(
        &hspi1,
        TCS_GPIO_Port,
        TCS_Pin
    );

    XPT2046_LVGL_Init();


    /* ---------------------------------------------------------------------- */
    /* EEZ Studio UI                                                           */
    /* ---------------------------------------------------------------------- */

    ui_init();


    /* ---------------------------------------------------------------------- */
    /* Pages                                                                    */
    /* ---------------------------------------------------------------------- */

    MainPage_Init();

    TempPage_Init();


    /* ---------------------------------------------------------------------- */
    /* Tasks                                                                    */
    /* ---------------------------------------------------------------------- */

    Tasks_Init();
}


/* -------------------------------------------------------------------------- */
/* Application Run                                                            */
/* -------------------------------------------------------------------------- */

void Application_Run(void)
{
    Tasks_Run();
}
